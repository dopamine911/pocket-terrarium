#!/usr/bin/env python3
"""gen_icons.py - bake assets/icons/*.png into common/icons.h + the icon sources, one file per owner:
    common/icons.c                      the art both worlds share
    common/worlds/aquarium/icons.c      the aquarium's half of every pair (<name>.png that has a <name>_terr.png)
    common/worlds/terrarium/icons.c     the terrarium's art (<name>_terr.png: the half of a pair, and its own pieces)
(sim/Makefile and firmware/components/tankcore/CMakeLists.txt compile only the build's world's file, so a one-world
bin carries only its own pixels; the files hold no #if.)

Full-color pixel-art icons, hand-drawn (the style: 16/24 px, hard edges,
three-tone shading). Each PNG becomes an icon_t: RGB565
pixels + an 8-bit alpha plane, blended at draw time by render.c's
blit_icon() (which can also scale alpha for dimming/unrevealed states).

Per-world art: <name>_terr.png (tools/gen_terr_icons.py) replaces <name>.png in the
terrarium's bin (common/world.h PT_TERRARIUM). Both are declared; each bin defines
only its own world's (the files above), and WORLD_ICON(icon_<name>) picks it. A <name>_terr.png with
no <name>.png is the terrarium's own (its shop pieces, its shed badges): defined in
the terrarium's bin alone, named as icon_<name>_terr in terrarium-only code.

Run from anywhere; paths are repo-relative to this file:
    python3 tools/gen_icons.py
"""
import os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "icons")
OUT_C = os.path.join(ROOT, "common", "icons.c")
OUT_AQ = os.path.join(ROOT, "common", "worlds", "aquarium", "icons.c")
OUT_TERR = os.path.join(ROOT, "common", "worlds", "terrarium", "icons.c")
OUT_H = os.path.join(ROOT, "common", "icons.h")


def cname(fn):
    stem = os.path.splitext(fn)[0]
    return "icon_" + re.sub(r"[^a-z0-9]+", "_", stem.replace("icon_", "").lower()).strip("_")


TERR = "_terr"


def main():
    files = sorted(f for f in os.listdir(SRC) if f.endswith(".png"))
    if not files:
        sys.exit(f"no PNGs in {SRC}")
    stems = {os.path.splitext(f)[0] for f in files}
    terr_of = {s[: -len(TERR)] for s in stems if s.endswith(TERR)}   # the aquarium names that have a terrarium variant ...
    terr_only = sorted(terr_of - stems)                                # ... and the terrarium's own art (no aquarium original)
    terr_of &= stems
    decls, pairs = [], []
    defs = {"": [], "aquarium": [], "terrarium": []}      # the file each icon is baked into
    table = {"": [], "aquarium": [], "terrarium": []}
    total = 0
    for fn in files:
        img = Image.open(os.path.join(SRC, fn)).convert("RGBA")
        w, h = img.size
        if w > 64 or h > 64:
            sys.exit(f"{fn}: {w}x{h} is too big for a UI icon (max 64)")
        px = list(img.getdata())
        rgb, alp = [], []
        for r, g, b, a in px:
            rgb.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
            alp.append(a)
        n = cname(fn)
        stem = os.path.splitext(fn)[0]
        owner = "terrarium" if stem.endswith(TERR) else "aquarium" if stem in terr_of else ""
        if stem in terr_of:
            pairs.append(n)
        total += w * h * 3
        defs[owner].append(f"static const uint16_t {n}_rgb[{w * h}] = {{\n"
                           + wrap(", ".join(f"0x{v:04x}" for v in rgb)) + "\n};\n\n"
                           + f"static const uint8_t {n}_a[{w * h}] = {{\n"
                           + wrap(", ".join(str(v) for v in alp)) + "\n};")
        table[owner].append(f"const icon_t {n} = {{ {w}, {h}, {n}_rgb, {n}_a }};")
        decls.append(f"extern const icon_t {n};")
    hdr = (
        "/* icons.h - GENERATED by tools/gen_icons.py from the assets/icons PNGs.\n"
        " * Do not edit by hand; re-run the script after changing the art. */\n"
        "#ifndef POCKET_TANK_ICONS_H\n#define POCKET_TANK_ICONS_H\n"
        "#include <stdint.h>\n#include \"world.h\"\n\n"
        "typedef struct { uint8_t w, h; const uint16_t *rgb; const uint8_t *a; } icon_t;\n\n"
        + "\n".join(decls) + "\n\n"
        "/* the per-world art: icon_<name>_terr in the terrarium's bin, icon_<name> in the aquarium's. Each bin defines\n"
        " * only its own of the pair (worlds/<world>/icons.c), so name one only through WORLD_ICON (a constant choice, folded away):\n"
        + "".join(f" *   {' '.join(pairs[i:i + 4])}\n" for i in range(0, len(pairs), 4)) + " * The terrarium's own art, defined in its bin alone (name it in terrarium-only code):\n"
        + "".join(f" *   {' '.join(cname(s + TERR) for s in terr_only[i:i + 4])}\n" for i in range(0, len(terr_only), 4)) + " */\n"
        "#define WORLD_ICON(name) (PT_TERRARIUM ? &name##_terr : &name)\n"
        "\n#endif\n")
    names = {"": ("icons.c", OUT_C, "the art both worlds share"),
             "aquarium": ("worlds/aquarium/icons.c", OUT_AQ, "the aquarium's art (compiled in its bin alone)"),
             "terrarium": ("worlds/terrarium/icons.c", OUT_TERR, "the terrarium's art (compiled in its bin alone)")}
    open(OUT_H, "w").write(hdr)
    for owner, (label, path, what) in names.items():
        src = (f"/* {label} - GENERATED by tools/gen_icons.py from the assets/icons PNGs: {what}. */\n"
               + '#include "icons.h"\n\n' + "\n\n".join(defs[owner]) + "\n\n" + "\n".join(table[owner]) + "\n")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write(src)
    print(f"wrote {len(files)} icons ({len(pairs)} with a terrarium variant, {len(terr_only)} the terrarium's own), {total / 1024:.1f} KB of pixel data in all")
    for f in files:
        print(f"  {cname(f)}")


def wrap(s, width=100):
    out, line = [], "    "
    for tok in s.split(", "):
        if len(line) + len(tok) + 2 > width:
            out.append(line.rstrip())
            line = "    "
        line += tok + ", "
    out.append(line.rstrip().rstrip(","))
    return "\n".join(out)


if __name__ == "__main__":
    main()
